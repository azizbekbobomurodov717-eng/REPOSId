from tkinter import *

def change_color(rang):
    root.config(bg=rang)

root = Tk()
root.title("Change bg color! ")
root.geometry("1300x850")

red_btn = Button(root,width="9", height="3", text="red", bg="red", fg="white", font=
("Ariel", 15), command=lambda: change_color("red"))
red_btn.pack()


